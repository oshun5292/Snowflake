-- MCPサーバー専用のロール・ユーザー(サービスアカウント)を作成し、
-- SHUN_DEV_DB に対する最小権限を付与する。
--
-- 設計方針:
--   - RAW スキーマ         : 生データそのもの。誤って書き換えられると元に戻せないため SELECT のみ。
--   - STAGING/INTERMEDIATE/MARTS : dbt が作る VIEW 層。壊れても dbt run で再生成できるため全操作を許可。
--   - このロールには「他のユーザー/ロールに権限を付与する権限」は一切与えない
--     (WITH GRANT OPTION、MANAGE GRANTS、CREATE ROLE/USER などは含めない)。

USE ROLE SECURITYADMIN;

-- 1. 専用ロールの作成
CREATE ROLE IF NOT EXISTS MCP_SERVER_ROLE
  COMMENT = 'Role used by the Snowflake MCP Server (SHUN_DEV_MCP_SERVER) to access SHUN_DEV_DB';

-- 権限の管理階層から見えるように SYSADMIN 配下にぶら下げておく(Snowflakeの定石)
GRANT ROLE MCP_SERVER_ROLE TO ROLE SYSADMIN;

-- 2. 専用ユーザー(サービスアカウント)の作成
-- TYPE = SERVICE : 人間ではなくプログラムが使うアカウントであることを明示する。
--                  この指定によりパスワードでのログインができなくなり、鍵ペア認証のみに限定できる。
-- RSA_PUBLIC_KEY  : 事前に鍵ペアを生成し、公開鍵の中身(ヘッダー/フッター行を除いた本体)を貼り付けること。
--                  鍵ペアの作り方: https://docs.snowflake.com/en/user-guide/key-pair-auth
CREATE USER IF NOT EXISTS MCP_SERVER_USER
  TYPE = SERVICE
  DEFAULT_ROLE = MCP_SERVER_ROLE
  DEFAULT_WAREHOUSE = SHUN_DEV_WH
  RSA_PUBLIC_KEY = '<公開鍵の中身をここに貼り付け>'
  COMMENT = 'Service account for Snowflake MCP Server (SHUN_DEV_MCP_SERVER)';

GRANT ROLE MCP_SERVER_ROLE TO USER MCP_SERVER_USER;

-- 3. ウェアハウス・データベースの利用権限
GRANT USAGE ON WAREHOUSE SHUN_DEV_WH TO ROLE MCP_SERVER_ROLE;
GRANT USAGE ON DATABASE SHUN_DEV_DB TO ROLE MCP_SERVER_ROLE;

-- 4. RAW スキーマ: 閲覧のみ
GRANT USAGE ON SCHEMA SHUN_DEV_DB.RAW TO ROLE MCP_SERVER_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA SHUN_DEV_DB.RAW TO ROLE MCP_SERVER_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA SHUN_DEV_DB.RAW TO ROLE MCP_SERVER_ROLE;
GRANT SELECT ON ALL VIEWS IN SCHEMA SHUN_DEV_DB.RAW TO ROLE MCP_SERVER_ROLE;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA SHUN_DEV_DB.RAW TO ROLE MCP_SERVER_ROLE;

-- 5. STAGING スキーマ: 全操作を許可(VIEW層)
GRANT ALL PRIVILEGES ON SCHEMA SHUN_DEV_DB.STAGING TO ROLE MCP_SERVER_ROLE;
GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA SHUN_DEV_DB.STAGING TO ROLE MCP_SERVER_ROLE;
GRANT ALL PRIVILEGES ON FUTURE TABLES IN SCHEMA SHUN_DEV_DB.STAGING TO ROLE MCP_SERVER_ROLE;
GRANT ALL PRIVILEGES ON ALL VIEWS IN SCHEMA SHUN_DEV_DB.STAGING TO ROLE MCP_SERVER_ROLE;
GRANT ALL PRIVILEGES ON FUTURE VIEWS IN SCHEMA SHUN_DEV_DB.STAGING TO ROLE MCP_SERVER_ROLE;

-- 6. INTERMEDIATE スキーマ: 全操作を許可(VIEW層)
GRANT ALL PRIVILEGES ON SCHEMA SHUN_DEV_DB.INTERMEDIATE TO ROLE MCP_SERVER_ROLE;
GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA SHUN_DEV_DB.INTERMEDIATE TO ROLE MCP_SERVER_ROLE;
GRANT ALL PRIVILEGES ON FUTURE TABLES IN SCHEMA SHUN_DEV_DB.INTERMEDIATE TO ROLE MCP_SERVER_ROLE;
GRANT ALL PRIVILEGES ON ALL VIEWS IN SCHEMA SHUN_DEV_DB.INTERMEDIATE TO ROLE MCP_SERVER_ROLE;
GRANT ALL PRIVILEGES ON FUTURE VIEWS IN SCHEMA SHUN_DEV_DB.INTERMEDIATE TO ROLE MCP_SERVER_ROLE;

-- 7. MARTS スキーマ: 全操作を許可(VIEW層)
GRANT ALL PRIVILEGES ON SCHEMA SHUN_DEV_DB.MARTS TO ROLE MCP_SERVER_ROLE;
GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA SHUN_DEV_DB.MARTS TO ROLE MCP_SERVER_ROLE;
GRANT ALL PRIVILEGES ON FUTURE TABLES IN SCHEMA SHUN_DEV_DB.MARTS TO ROLE MCP_SERVER_ROLE;
GRANT ALL PRIVILEGES ON ALL VIEWS IN SCHEMA SHUN_DEV_DB.MARTS TO ROLE MCP_SERVER_ROLE;
GRANT ALL PRIVILEGES ON FUTURE VIEWS IN SCHEMA SHUN_DEV_DB.MARTS TO ROLE MCP_SERVER_ROLE;
